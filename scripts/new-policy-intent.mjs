// Generate a ready-to-validate registry policy intent for YOUR wallet.
//
//   node scripts/new-policy-intent.mjs --controller 0x... [--agent 0x...] \
//     [--per-tx-usd 1.5] [--epoch-usd 25] [--epoch-hours 24] \
//     [--merchants mcp_search,vector_cloud] [--out ops/my_policy_intent.json]
//
// Writes the intent file and immediately runs it through the dry-run
// validator, printing the createPolicy calldata and expected policyId.
// Nothing is signed or sent; sending stays with the controller wallet owner
// (npm run send-registry-intent -- <report>).

import { writeFileSync, mkdirSync } from "node:fs";
import { keccak256, stringToHex } from "viem";
import { allowanceRegistryDeployment } from "../src/deployments.mjs";
import { buildRegistryPolicyIntent } from "../src/registryPolicyIntent.mjs";

const args = {};
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i += 2) {
  if (!argv[i].startsWith("--")) continue;
  args[argv[i].slice(2)] = argv[i + 1];
}

const controller = args.controller;
if (!/^0x[0-9a-fA-F]{40}$/.test(controller || "")) {
  console.error("Required: --controller 0x<your wallet>. This wallet sends createPolicy and controls the policy.");
  process.exit(1);
}
const agent = args.agent || controller;
if (!/^0x[0-9a-fA-F]{40}$/.test(agent)) {
  console.error("--agent must be a 20-byte address (the wallet your agent pays from)");
  process.exit(1);
}

const deployment = allowanceRegistryDeployment("base");
const merchants = String(args.merchants || "mcp_search,vector_cloud,lead_graph").split(",").map((m) => m.trim()).filter(Boolean);
const nonce = keccak256(stringToHex(`allow-policy:${controller}:${Date.now()}`));

const registry = {
  contractAddress: deployment.address,
  chainId: deployment.chainId,
  network: "Base",
  environment: "mainnet",
  controller,
  agentAddress: agent,
  settlementToken: "0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02913",
  controllerNonce: nonce,
  epochCapUsd: Number(args["epoch-usd"] || 25),
  perTxCapUsd: Number(args["per-tx-usd"] || 1.5),
  epochSeconds: Math.round(Number(args["epoch-hours"] || 24) * 3600),
  amountDecimals: 6
};

const intent = {
  intentId: `policy-${controller.slice(2, 10).toLowerCase()}-${new Date().toISOString().slice(0, 10)}`,
  policyPath: "allow-policy.example.json",
  requireDeployedRegistry: true,
  registry,
  merchants,
  notes: [
    "Generated by scripts/new-policy-intent.mjs. Review the caps and merchant list, then send from the controller wallet.",
    "The controllerNonce is a public, non-secret uniqueness value."
  ]
};

const outPath = args.out || `ops/policy_intent_${controller.slice(2, 8).toLowerCase()}.local.json`;
writeFileSync(outPath, JSON.stringify(intent, null, 2) + "\n");

// The report written here is the single source of truth for sending: it is
// built from the SAME merchants/caps as the intent file, so the expected
// policyId and the sent calldata cannot drift apart.
const policy = { allowedMerchants: merchants, perTxCapUsd: registry.perTxCapUsd, dailyCapUsd: registry.epochCapUsd };
const report = buildRegistryPolicyIntent(policy, { ...registry, requireDeployedRegistry: true });

mkdirSync("work/registry", { recursive: true });
const reportPath = args["report-out"] || "work/registry/my-policy.report.json";
writeFileSync(reportPath, JSON.stringify({ intentPath: outPath, ...report }, null, 2) + "\n");

console.log(`Intent written: ${outPath}`);
console.log(`Report written: ${reportPath}`);
console.log(`  valid:            ${report.valid}${report.valid ? "" : " — " + JSON.stringify(report.reasons)}`);
console.log(`  expected policyId: ${report.registry.expectedPolicyId}`);
console.log(`  caps:             $${registry.perTxCapUsd}/tx, $${registry.epochCapUsd}/${registry.epochSeconds / 3600}h`);
console.log(`  merchants:        ${merchants.join(", ")}`);
console.log(`\nNext (from the controller wallet):`);
console.log(`  npm run send-registry-intent -- ${reportPath}`);
process.exit(report.valid ? 0 : 1);
